"""Generates EssentialViewS3/web_fonts.h: the two Essentialsail fonts (assets/fonts/*.ttf, SIL OFL) as byte arrays in flash.
The watch serves them to the configuration web page at /fonts/<name>.ttf, so the page uses the Essentialsail
typefaces without Internet access.

Usage:  python tools/make_webfonts.py        (from the repository root)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = os.path.join(HERE, "..", "assets", "fonts")
OUT = os.path.join(HERE, "..", "EssentialViewS3", "web_fonts.h")
ITEMS = [("FONT_DISPLAY", "EssentialsailDisplay-Bold.ttf"), ("FONT_TEXT", "EssentialsailText-Regular.ttf")]

lines = ["// Generated by tools/make_webfonts.py - do not edit. Essentialsail fonts (SIL Open Font License, assets/fonts/OFL.txt).",
         "#pragma once", "#include <pgmspace.h>", ""]
for name, fn in ITEMS:
    data = open(os.path.join(FONTS, fn), "rb").read()
    lines.append(f"// {fn} ({len(data)} bytes)")
    lines.append(f"const size_t {name}_LEN = {len(data)};")
    lines.append(f"const uint8_t {name}[] PROGMEM = {{")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append("")
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("written", OUT, sum(os.path.getsize(os.path.join(FONTS, f)) for _, f in ITEMS), "bytes of fonts")
